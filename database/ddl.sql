-- 기존 테이블 삭제 (외래키 의존성 역순)
DROP TABLE RECIPE_INGREDIENTS  CASCADE CONSTRAINTS;
DROP TABLE RECIPES             CASCADE CONSTRAINTS;
DROP TABLE USER_INGREDIENTS    CASCADE CONSTRAINTS;
DROP TABLE USER_DIET_PREFERENCES CASCADE CONSTRAINTS;
DROP TABLE SCAN_HISTORY        CASCADE CONSTRAINTS;
DROP TABLE USER_ALLERGIES      CASCADE CONSTRAINTS;
DROP TABLE USERS               CASCADE CONSTRAINTS;

-- 1. USERS (회원)
CREATE TABLE USERS (
    USER_ID  NUMBER        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    EMAIL    VARCHAR2(100) NOT NULL UNIQUE,
    USER_PWD VARCHAR2(255) NOT NULL,
    LOGIN_ID VARCHAR2(50)  NOT NULL CONSTRAINT UQ_USERS_LOGIN_ID UNIQUE,
    USERNAME VARCHAR2(50)  NOT NULL CONSTRAINT UQ_USERS_USERNAME UNIQUE,
    PHONE    VARCHAR2(20)
);

-- 2. USER_ALLERGIES (알레르기 정보)
CREATE TABLE USER_ALLERGIES (
    ALLERGY_ID NUMBER        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID    NUMBER        NOT NULL,
    ALLERGEN   VARCHAR2(100) NOT NULL,
    CONSTRAINT FK_UA_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 3. SCAN_HISTORY (냉장고 스캔 이력)
CREATE TABLE SCAN_HISTORY (
    SCAN_ID         NUMBER       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER       NOT NULL,
    IMAGE_URL       VARCHAR2(500),
    RECOGNIZED_JSON CLOB,
    CREATED_AT      TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_SH_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 4. USER_DIET_PREFERENCES (식이 선호도)
CREATE TABLE USER_DIET_PREFERENCES (
    PREFERENCE_ID NUMBER      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID       NUMBER      NOT NULL,
    DIET_TYPE     VARCHAR2(50) NOT NULL,
    CONSTRAINT FK_UDP_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 5. USER_INGREDIENTS (냉장고 식재료)
CREATE TABLE USER_INGREDIENTS (
    USER_INGREDIENT_ID NUMBER        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID            NUMBER        NOT NULL,
    INGREDIENT_NAME    VARCHAR2(100) NOT NULL,
    QUANTITY           VARCHAR2(50),
    EXPIRY_DATE        DATE,
    ADDED_METHOD       VARCHAR2(20)  DEFAULT 'MANUAL',
    STATUS             VARCHAR2(20)  DEFAULT 'ACTIVE',
    CREATED_AT         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_UI_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 6. RECIPES (AI 추천 레시피)
CREATE TABLE RECIPES (
    RECIPE_ID     NUMBER        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID       NUMBER        NOT NULL,
    TITLE         VARCHAR2(200) NOT NULL,
    DESCRIPTION   CLOB,
    COOKING_TIME  NUMBER,
    DIFFICULTY    VARCHAR2(20),
    SERVINGS      NUMBER,
    YOUTUBE_URL   VARCHAR2(500),
    YOUTUBE_TITLE VARCHAR2(300),
    IS_SAVED      NUMBER(1,0)   DEFAULT 0,
    CREATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_R_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 7. RECIPE_INGREDIENTS (레시피 필요 재료)
CREATE TABLE RECIPE_INGREDIENTS (
    RECIPE_ING_ID   NUMBER        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RECIPE_ID       NUMBER        NOT NULL,
    INGREDIENT_NAME VARCHAR2(100) NOT NULL,
    AMOUNT          VARCHAR2(50),
    IS_AVAILABLE    NUMBER(1,0)   DEFAULT 0,
    CONSTRAINT FK_RI_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPES(RECIPE_ID) ON DELETE CASCADE
);

COMMIT;

SELECT '=== 테이블 생성 완료 ===' AS STATUS FROM DUAL;
SELECT TABLE_NAME FROM USER_TABLES
WHERE TABLE_NAME IN (
    'USERS','USER_ALLERGIES','SCAN_HISTORY',
    'USER_DIET_PREFERENCES','USER_INGREDIENTS',
    'RECIPES','RECIPE_INGREDIENTS'
)
ORDER BY TABLE_NAME;
